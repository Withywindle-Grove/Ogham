// Builds docs/generated/commands.md (every command, its log level, and who may and may not run it) from the
// command registry and the permission cases (src/testing/permissionCases.ts). `npm run docs:gen` writes it;
// otherwise this test fails when the committed file is out of date.
import { describe, expect, it } from 'vitest';
import { createAppRegistry } from '../app/commandRegistry.ts';
import { permissionCases, type PermissionCase, type Who } from './permissionCases.ts';
import committedPage from '../../docs/generated/commands.md?raw';

// Node's own modules aren't typed in this project (browser types only), so they're reached loosely here.
const env = (globalThis as unknown as { process: { env: Record<string, string | undefined> } }).process.env;

const FILE = 'docs/generated/commands.md';
const WHO: Record<Who, string> = { gm: 'GM', playerA: 'Player A', playerB: 'Player B', outsider: 'Outsider', newcomer: 'Newcomer' };

const escape = (text: string) => text.replace(/\|/g, '\\|');
const list = (cases: PermissionCase[]) =>
  cases.length ? cases.map((c) => `${WHO[c.who]}: ${escape(c.says)}`).join('<br>') : '—';

export function commandsMarkdown(): string {
  const registry = createAppRegistry();
  const rows = registry.names().map((name) => {
    const cases = permissionCases.filter((c) => c.commandName === name);
    return `| \`${name}\` | ${registry.logLevel(name)} | ${list(cases.filter((c) => c.allowed))} | ${list(cases.filter((c) => !c.allowed))} |`;
  });
  return [
    '# Commands (generated)',
    '',
    'Generated by `npm run docs:gen` from the command registry (`src/app/commandRegistry.ts`) and the permission cases (`src/testing/permissionCases.ts`). Do not edit by hand. `npm test` fails when this file is out of date.',
    '',
    'Every change goes through one of these commands, which checks `can(user, command, target)` and writes an event. "Log" is where its events show: simple (the default view), verbose (everything) or none (account-level, not a campaign event). The cases are the same ones `npm test` checks against the app and `npm run test:db` checks against the test database. Who: the GM, Player A and Player B (members of the campaign), an Outsider (signed in, not a member) and a Newcomer (holding an invite).',
    '',
    '| Command | Log | Allowed (examples) | Not allowed (examples) |',
    '|---|---|---|---|',
    ...rows,
    '',
  ].join('\n');
}

describe('the generated command list', () => {
  it('is up to date with the registry and the permission cases (run npm run docs:gen if this fails)', async () => {
    const page = commandsMarkdown();
    if (env.DOCS_GEN === '1') {
      const fs = (await import(/* @vite-ignore */ 'node:' + 'fs')) as { writeFileSync(path: string, text: string): void };
      fs.writeFileSync(FILE, page);
      return;
    }
    expect(committedPage.replace(/\r\n/g, '\n'), `${FILE} is out of date: run npm run docs:gen and commit the result.`).toBe(page);
  });
});
