// Builds docs/generated/visibility-matrix.md: for each public table, which access rules (row-level security
// policies) let someone read, add, change or delete rows. It replays the migrations in order (create, drop and
// rename of policies), so it shows the rules as they stand after the last migration.
// Run through `npm run docs:gen`; `npm test` fails if the committed file is out of date.
import { readFileSync, readdirSync } from 'node:fs';
import { join } from 'node:path';

const ACTIONS = ['select', 'insert', 'update', 'delete'];
const HEADINGS = { select: 'Read', insert: 'Add', update: 'Change', delete: 'Delete' };

/** Removes SQL comments (-- to the end of the line, and block comments). */
function stripComments(sql) {
  return sql.replace(/\/\*[\s\S]*?\*\//g, ' ').replace(/--[^\n]*/g, ' ');
}

const unquote = (name) => name.replace(/^"|"$/g, '');
const tableKey = (raw) => {
  const parts = raw.split('.').map(unquote);
  return parts.length === 2 ? `${parts[0]}.${parts[1]}` : `public.${parts[0]}`;
};

/**
 * Replays the policy statements of the migrations, in order.
 * Returns { tables: Map<table, Map<policyName, {action, restrictive}>>, rls: Set<table> }.
 */
export function replayPolicies(sqlTexts) {
  const tables = new Map();
  const rls = new Set();
  const table = (key) => tables.get(key) ?? tables.set(key, new Map()).get(key);
  const statement =
    /create\s+policy\s+("[^"]+"|\w+)\s+on\s+([\w."]+)([^;]*);|drop\s+policy\s+(?:if\s+exists\s+)?("[^"]+"|\w+)\s+on\s+([\w."]+)|alter\s+policy\s+("[^"]+"|\w+)\s+on\s+([\w."]+)\s+rename\s+to\s+("[^"]+"|\w+)|alter\s+table\s+(?:only\s+)?([\w."]+)\s+enable\s+row\s+level\s+security/gi;
  for (const sql of sqlTexts) {
    for (const m of stripComments(sql).matchAll(statement)) {
      if (m[1]) {
        const body = m[3];
        const action = (/\bfor\s+(select|insert|update|delete|all)\b/i.exec(body)?.[1] ?? 'all').toLowerCase();
        table(tableKey(m[2])).set(unquote(m[1]), { action, restrictive: /\bas\s+restrictive\b/i.test(body) });
      } else if (m[4]) {
        tables.get(tableKey(m[5]))?.delete(unquote(m[4]));
      } else if (m[6]) {
        const policies = tables.get(tableKey(m[7]));
        const old = policies?.get(unquote(m[6]));
        if (policies && old) {
          policies.delete(unquote(m[6]));
          policies.set(unquote(m[8]), old);
        }
      } else if (m[9]) {
        rls.add(tableKey(m[9]));
      }
    }
  }
  return { tables, rls };
}

/** The Markdown page. Only tables in the public schema (the ones the app reaches) are listed. */
export function visibilityMarkdown({ tables, rls }) {
  const names = [...new Set([...tables.keys(), ...rls])].filter((t) => t.startsWith('public.')).sort();
  const cell = (policies, action) => {
    const rules = [...policies.entries()]
      .filter(([, p]) => p.action === action || p.action === 'all')
      .map(([name, p]) => {
        const short = name.includes(': ') ? name.slice(name.indexOf(': ') + 2) : name;
        return p.restrictive ? `only if: ${short}` : short;
      })
      .sort();
    return rules.length ? rules.join('; ') : '—';
  };
  const rows = names.map((name) => {
    const policies = tables.get(name) ?? new Map();
    return `| \`${name.slice('public.'.length)}\` | ${ACTIONS.map((a) => cell(policies, a)).join(' | ')} |`;
  });
  return [
    '# Visibility matrix (generated)',
    '',
    'Generated by `npm run docs:gen` from the access rules (row-level security policies) in `supabase/migrations/`, replayed in order. Do not edit by hand. `npm test` fails when this file is out of date.',
    '',
    'Each cell lists the rules that let a signed-in person do that to a row (the rule names say who). "—" means no rule allows it directly: only the database\'s own functions can, after their own checks. "only if" marks a rule that narrows the others. The real check is the database itself: `npm run test:db` runs every permission case against the test project.',
    '',
    `| Table | ${ACTIONS.map((a) => HEADINGS[a]).join(' | ')} |`,
    `|---|${ACTIONS.map(() => '---').join('|')}|`,
    ...rows,
    '',
  ].join('\n');
}

/** Reads every migration in name order and builds the page. */
export function buildVisibilityMatrix(migrationsDir = 'supabase/migrations') {
  const files = readdirSync(migrationsDir).filter((f) => f.endsWith('.sql')).sort();
  return visibilityMarkdown(replayPolicies(files.map((f) => readFileSync(join(migrationsDir, f), 'utf8'))));
}
